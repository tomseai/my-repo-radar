import { access, mkdir, readFile, readdir, unlink, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

import { parse } from "yaml";

import type { CatalogArtifact, CatalogRepository } from "./generate-catalog.js";

interface Taxonomy {
  primary_categories: string[];
  topics: string[];
}

export interface MarkdownPage {
  path: string;
  content: string;
}

const DISPLAY_WORDS: Record<string, string> = {
  ai: "AI",
  api: "API",
  apis: "APIs",
  cli: "CLI",
  cms: "CMS",
  devops: "DevOps",
  github: "GitHub",
  llm: "LLM",
  llms: "LLMs",
  mcp: "MCP",
  ui: "UI",
  tui: "TUI",
};

export function displayName(slug: string): string {
  return slug.split("-").map((word, index) => {
    if (DISPLAY_WORDS[word]) return DISPLAY_WORDS[word];
    if (index > 0 && ["and", "for", "of", "to"].includes(word)) return word;
    return `${word.slice(0, 1).toUpperCase()}${word.slice(1)}`;
  }).join(" ");
}

function generatedNotice(): string {
  return "<!-- Generated by `npm run generate`. Do not edit manually. -->";
}

function inlineList(values: string[], empty = "Unknown"): string {
  return values.length > 0 ? values.join(", ") : empty;
}

function categoryLink(category: string | null, fromRoot: boolean): string {
  if (!category) return "Unknown";
  return `[${displayName(category)}](${fromRoot ? "" : "../"}categories/${category}.md)`;
}

function topicLinks(topics: string[], fromRoot: boolean): string {
  return topics.map((topic) => `[${displayName(topic)}](${fromRoot ? "" : "../"}topics/${topic}.md)`).join(" | ");
}

function summary(repository: CatalogRepository): string {
  return repository.project.summary ?? repository.github.description ?? "No summary is available.";
}

function repositoryDetails(repository: CatalogRepository): string {
  const license = repository.license.spdx ?? repository.license.name ?? "Unknown";
  const lifecycle = repository.status.lifecycle ? displayName(repository.status.lifecycle) : "Unknown";
  const features = repository.key_features.slice(0, 3).map((feature) => `  - ${feature}`).join("\n");
  const bestFor = repository.project.best_for.slice(0, 2).join("; ");
  return [
    `## [${repository.project.name}](${repository.identity.url})`,
    "",
    summary(repository),
    "",
    `- **Category:** ${categoryLink(repository.classification.primary_category, false)}`,
    `- **Topics:** ${topicLinks(repository.classification.topics, false) || "None"}`,
    `- **Kind:** ${repository.project.kind ? displayName(repository.project.kind) : "Unknown"}`,
    `- **Best for:** ${bestFor || "Not specified"}`,
    `- **Languages:** ${inlineList(repository.technology.languages)}`,
    `- **License:** ${license}`,
    `- **Lifecycle:** ${lifecycle}`,
    `- **GitHub stars:** ${repository.github.stars.toLocaleString("en-US")}`,
    "",
    "**Key features**",
    "",
    features || "  - Not specified",
  ].join("\n");
}

function renderReadme(catalog: CatalogArtifact, taxonomy: Taxonomy): string {
  const byCategory = new Map<string, CatalogRepository[]>();
  for (const category of taxonomy.primary_categories) byCategory.set(category, []);
  for (const repository of catalog.repositories) {
    const category = repository.classification.primary_category ?? "other";
    const repositories = byCategory.get(category) ?? [];
    repositories.push(repository);
    byCategory.set(category, repositories);
  }
  const lines = [
    generatedNotice(),
    "",
    "# my-repo-radar",
    "",
    "An evidence-backed catalog of the public GitHub repositories starred by [`tomseai`](https://github.com/tomseai?tab=stars). The collection covers all subjects, not only AI projects.",
    "",
    `The catalog currently contains **${catalog.counts.repositories} repositories**. Each repository appears once under its primary category and may also appear on several topic pages.`,
    "",
    "## Browse by primary category",
    "",
    ...[...byCategory.entries()].filter(([, repositories]) => repositories.length > 0).map(([category, repositories]) =>
      `- [${displayName(category)}](categories/${category}.md) (${repositories.length})`),
    "",
    "# Repositories by primary category",
  ];

  for (const [category, repositories] of byCategory) {
    if (repositories.length === 0) continue;
    lines.push("", `## [${displayName(category)}](categories/${category}.md)`, "");
    for (const repository of repositories) {
      lines.push(`- **[${repository.project.name}](${repository.identity.url})** - ${summary(repository)}`);
      lines.push(`  Topics: ${topicLinks(repository.classification.topics, true) || "None"}`);
    }
  }

  lines.push(
    "",
    "## Data and maintenance",
    "",
    "The canonical data lives in `data/repositories/` and `data/dossiers/`. Generated JSON and Markdown are deterministic and must not be edited manually.",
    "",
    "This project is licensed under the [Apache License 2.0](LICENSE).",
    "",
    "```sh",
    "npm install",
    "npm run generate",
    "npm run validate",
    "npm test",
    "```",
    "",
    "See [`docs/generated-catalog.md`](docs/generated-catalog.md) for the generated data contracts and freshness rules.",
  );
  return `${lines.join("\n")}\n`;
}

function renderCategory(category: string, repositories: CatalogRepository[]): string {
  const topicCounts = new Map<string, number>();
  for (const repository of repositories) {
    for (const topic of repository.classification.topics) topicCounts.set(topic, (topicCounts.get(topic) ?? 0) + 1);
  }
  const lines = [
    generatedNotice(),
    "",
    `# ${displayName(category)}`,
    "",
    `[Back to the main catalog](../README.md) | **${repositories.length} repositories**`,
    "",
    "## Topics in this category",
    "",
    ...[...topicCounts.entries()].sort(([left], [right]) => left.localeCompare(right, "en")).map(([topic, count]) =>
      `- [${displayName(topic)}](../topics/${topic}.md) (${count})`),
  ];
  for (const repository of repositories) lines.push("", repositoryDetails(repository));
  return `${lines.join("\n")}\n`;
}

function renderTopic(topic: string, repositories: CatalogRepository[]): string {
  const categoryCounts = new Map<string, number>();
  for (const repository of repositories) {
    const category = repository.classification.primary_category ?? "other";
    categoryCounts.set(category, (categoryCounts.get(category) ?? 0) + 1);
  }
  const lines = [
    generatedNotice(),
    "",
    `# ${displayName(topic)}`,
    "",
    `[Back to the main catalog](../README.md) | **${repositories.length} repositories**`,
    "",
    "## Primary categories represented",
    "",
    ...[...categoryCounts.entries()].sort(([left], [right]) => left.localeCompare(right, "en")).map(([category, count]) =>
      `- [${displayName(category)}](../categories/${category}.md) (${count})`),
  ];
  for (const repository of repositories) lines.push("", repositoryDetails(repository));
  return `${lines.join("\n")}\n`;
}

export function buildMarkdownPages(catalog: CatalogArtifact, taxonomy: Taxonomy): MarkdownPage[] {
  const pages: MarkdownPage[] = [{ path: "README.md", content: renderReadme(catalog, taxonomy) }];
  for (const category of taxonomy.primary_categories) {
    const repositories = catalog.repositories.filter((repository) => repository.classification.primary_category === category);
    if (repositories.length > 0) pages.push({ path: `categories/${category}.md`, content: renderCategory(category, repositories) });
  }
  const usedTopics = new Set(catalog.repositories.flatMap((repository) => repository.classification.topics));
  for (const topic of taxonomy.topics) {
    if (!usedTopics.has(topic)) continue;
    const repositories = catalog.repositories.filter((repository) => repository.classification.topics.includes(topic));
    pages.push({ path: `topics/${topic}.md`, content: renderTopic(topic, repositories) });
  }
  return pages;
}

async function exists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

async function pageFiles(root: string, directory: "categories" | "topics"): Promise<string[]> {
  const path = join(root, directory);
  if (!await exists(path)) return [];
  return (await readdir(path)).filter((file) => file.endsWith(".md")).map((file) => `${directory}/${file}`).sort();
}

async function main(): Promise<void> {
  const check = process.argv.slice(2).includes("--check");
  const root = resolve(process.cwd());
  const catalog = JSON.parse(await readFile(join(root, "generated", "catalog.json"), "utf8")) as CatalogArtifact;
  const taxonomy = parse(await readFile(join(root, "data", "taxonomy.yaml"), "utf8")) as Taxonomy;
  const pages = buildMarkdownPages(catalog, taxonomy);
  const expected = new Set(pages.map((page) => page.path));
  const existing = ["README.md", ...await pageFiles(root, "categories"), ...await pageFiles(root, "topics")];

  if (check) {
    const stale: string[] = [];
    for (const page of pages) {
      const path = join(root, page.path);
      if (!await exists(path) || await readFile(path, "utf8") !== page.content) stale.push(page.path);
    }
    const orphaned = existing.filter((path) => !expected.has(path));
    if (stale.length > 0 || orphaned.length > 0) {
      throw new Error(`Generated pages are stale (changed or missing: ${stale.length}; orphaned: ${orphaned.length}). Run npm run generate.`);
    }
    console.log(`Generated pages are current (${pages.length} pages).`);
    return;
  }

  await mkdir(join(root, "categories"), { recursive: true });
  await mkdir(join(root, "topics"), { recursive: true });
  await Promise.all(existing.filter((path) => !expected.has(path)).map((path) => unlink(join(root, path))));
  await Promise.all(pages.map(async (page) => {
    await mkdir(dirname(join(root, page.path)), { recursive: true });
    await writeFile(join(root, page.path), page.content, "utf8");
  }));
  console.log(`Generated ${pages.length} Markdown pages.`);
}

